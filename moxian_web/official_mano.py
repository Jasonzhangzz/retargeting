"""Unmodified MANO model and the upstream smplx implementation.

The inherited reader only supplies anatomical labels to existing contact code.
Geometry uses upstream MANO, identified glove dimensions and an optional fixed
rest-surface compensation generated by offline spatial EMA.
"""
import numpy as np
import torch
from smplx import MANO
from smplx.utils import Struct
from smplx.lbs import batch_rodrigues,lbs,batch_rigid_transform
from scripts.calibrate_wuji_mano import PersonalizedMANO, _ManoReader, as_array

OFFICIAL_MANO_MODE='official_mano_betas_v1'
OFFICIAL_REFERENCE_POLICY='official_pose_rigid_emf_reference_v1'

class OfficialMANO(PersonalizedMANO):
    def __init__(self,path,side='left'):
        with open(path,'rb') as stream:
            data=_ManoReader(stream,encoding='latin1').load()
        if any(str(k).startswith('retarget_') for k in data):
            raise ValueError('必须使用原始 MANO 权重，不能加载本地导出的定制模型')
        super().__init__(path,side)
        # Convert legacy Chumpy/sparse containers without altering their values.
        fields={k:as_array(data[k]) for k in ('v_template','shapedirs','posedirs','J_regressor','weights','hands_components','hands_mean','kintree_table','f')}
        self.backend=MANO(str(path),data_struct=Struct(**fields),is_rhand=side=='right',
                          use_pca=False,flat_hand_mean=True,num_betas=10,
                          create_transl=False,dtype=torch.float32)
        parents=self.backend.parents.cpu().tolist();self.parent_indices=tuple(parents)
        self.rotation_levels=[]
        depth=[0]*16
        for j in range(1,16):depth[j]=depth[parents[j]]+1
        for d in range(1,4):
            ids=[j for j in range(1,16) if depth[j]==d]
            self.rotation_levels.append((ids,[parents[j] for j in ids]))
        self._rotation_indices={}
        self.glove_parameters = None
        # Fixed compensation for spatial EMA during offline calibration. This
        # is a buffer, never an independently optimized vertex parameter.
        self.register_buffer('rest_vertex_residual', torch.zeros_like(self.backend.v_template))
        self.surface_residual_enabled = False

    def official_rest(self,beta,geometry=None,apply_residual=True):
        v=self.backend.v_template+torch.einsum('vck,k->vc',self.backend.shapedirs,beta)
        j=self.backend.J_regressor@v
        geometry=self.glove_parameters if geometry is None else geometry
        if geometry is not None:
            from .glove_geometry import deform_rest
            from scripts.calibrate_wuji_mano import CHAINS,TIPS
            v,j=deform_rest(v,j,self.backend.lbs_weights,CHAINS,TIPS,self.palm_normal,geometry)
        return (v+self.rest_vertex_residual if apply_residual else v),j

    def official_forward(self,rest,joints,betas,pose):
        batch=pose.reshape(-1,45).shape[0]
        if self.glove_parameters is not None or self.surface_residual_enabled:
            from .card_math import exp_so3
            beta=torch.as_tensor(betas,device=pose.device,dtype=pose.dtype)
            return self.official_matrix_forward(beta,exp_so3(pose.reshape(batch,15,3)))
        # Tensor inputs must stay on the autograd graph during calibration.
        beta=torch.as_tensor(betas,device=pose.device,dtype=pose.dtype)
        if beta.ndim==1:beta=beta[None].expand(batch,-1)
        output=self.backend(betas=beta,hand_pose=pose.reshape(batch,45),
                            global_orient=torch.zeros((batch,3),device=pose.device,dtype=pose.dtype))
        aa=torch.cat((torch.zeros((batch,1,3),device=pose.device,dtype=pose.dtype),pose.reshape(batch,15,3)),dim=1)
        local=batch_rodrigues(aa.reshape(-1,3)).reshape(batch,16,3,3)
        rotations=self.absolute_rotations(local)
        return output.vertices,output.joints,rotations

    def absolute_rotations(self,local):
        # Functional tree evaluation avoids index_copy's in-place AOT backward
        # on constant expanded rest joints (PyTorch 2.10 CUDA).
        rotations=[local[:,0]]
        for joint in range(1,16):rotations.append(rotations[self.parent_indices[joint]]@local[:,joint])
        return torch.stack(rotations,1)

    def rigid_transforms(self,local,joints):
        rotations=self.absolute_rotations(local)
        centres=[joints[:,0]]
        for joint in range(1,16):
            parent=self.parent_indices[joint]
            delta=joints[:,joint]-joints[:,parent]
            centres.append(centres[parent]+(rotations[:,parent]@delta[...,None]).squeeze(-1))
        centres=torch.stack(centres,1)
        translation=centres-(rotations@joints[...,None]).squeeze(-1)
        top=torch.cat((rotations,translation[...,None]),-1)
        bottom=torch.cat((torch.zeros_like(top[...,:1,:3]),torch.ones_like(top[...,:1,:1])),-1)
        return centres,torch.cat((top,bottom),-2)

    def official_matrix_forward(self,betas,hand_rotations,geometry=None):
        """Upstream SMPL-X LBS matrix API; identical MANO pose correctives."""
        batch=len(hand_rotations)
        beta=betas[None].expand(batch,-1) if betas.ndim==1 else betas
        local=torch.cat((torch.eye(3,device=beta.device,dtype=beta.dtype)[None,None].expand(batch,1,3,3),hand_rotations),1)
        b=self.backend
        geometry=self.glove_parameters if geometry is None else geometry
        if geometry is not None:
            rest,j=self.official_rest(betas if betas.ndim==1 else betas[0],geometry)
            feature=(local[:,1:]-torch.eye(3,device=beta.device,dtype=beta.dtype)).reshape(batch,-1)
            posed=rest[None]+(feature@b.posedirs).reshape(batch,-1,3)
            joints,transforms=self.rigid_transforms(local,j[None].expand(batch,-1,-1))
            skin=(b.lbs_weights@transforms.reshape(batch,16,16)).reshape(batch,-1,4,4)
            homogeneous=torch.cat((posed,torch.ones_like(posed[...,:1])),dim=-1)
            vertices=(skin@homogeneous[...,None])[...,:3,0]
            return vertices,joints,self.absolute_rotations(local)
        vertices,joints=lbs(beta,local,b.v_template,b.shapedirs,b.posedirs,b.J_regressor,b.parents,b.lbs_weights,pose2rot=False)
        # A residual also works for legacy profiles without glove geometry.
        # Joint centres remain those of the identified skeleton.
        if self.surface_residual_enabled:
            shaped=b.v_template+torch.einsum('vck,bk->bvc',b.shapedirs,beta)
            _,transforms=self.rigid_transforms(local,b.J_regressor@shaped)
            skin=(b.lbs_weights@transforms.reshape(batch,16,16)).reshape(batch,-1,4,4)
            vertices=vertices+(skin[...,:3,:3]@self.rest_vertex_residual[None,...,None])[...,0]
        return vertices,joints,self.absolute_rotations(local)

    def official_batched_matrix_forward(self,betas,hand_rotations,geometry):
        """Same LBS values, with independently masked per-sample derivatives."""
        rest,rest_j=torch.vmap(self.official_rest)(betas,geometry)
        values=self.official_batched_rest_forward(hand_rotations,rest,rest_j)
        return *values,rest,rest_j

    def official_batched_rest_forward(self,hand_rotations,rest,rest_j):
        """LBS with an already computed batch of rest geometry."""
        batch=len(hand_rotations);b=self.backend
        eye=torch.eye(3,device=rest.device,dtype=rest.dtype)
        local=torch.cat((eye[None,None].expand(batch,1,3,3),hand_rotations),1)
        feature=(hand_rotations-eye).reshape(batch,-1)
        posed=rest+(feature@b.posedirs).reshape(batch,-1,3)
        joints,transforms=self.rigid_transforms(local,rest_j)
        skin=(b.lbs_weights@transforms.reshape(batch,16,16)).reshape(batch,-1,4,4)
        homogeneous=torch.cat((posed,torch.ones_like(posed[...,:1])),dim=-1)
        vertices=(skin@homogeneous[...,None])[...,:3,0]
        return vertices,joints,self.absolute_rotations(local)


def reference_from_frame(frame,weights_hash,serial,reference_id):
    from scipy.spatial.transform import Rotation
    fingers=('thumb','index','middle','ring','pinky')
    if not frame.get('skeleton'):raise ValueError('参考帧缺少同帧官方骨架')
    return {'pose':'flat_open','hand_side':frame.get('hand_side',frame['skeleton'].get('hand_side')),'observation_space':'raw_emf_sensor',
            'reference_policy':OFFICIAL_REFERENCE_POLICY,'skeleton':frame['skeleton'],
            'positions_local':[frame['fingers'][f]['position'] for f in fingers],
            'rotations_local':[Rotation.from_quat(frame['fingers'][f]['quaternion_xyzw']).as_matrix().ravel().tolist() for f in fingers],
            'timestamp_ms':frame['timestamp_ms'],'calibration_fingerprint':frame.get('calibration_fingerprint'),
            'skeleton_runtime_revision':frame.get('skeleton_runtime_revision'),
            'source':'official_eight_open_pose','reference_id':reference_id,'weights_hash':weights_hash,'serial':serial}
