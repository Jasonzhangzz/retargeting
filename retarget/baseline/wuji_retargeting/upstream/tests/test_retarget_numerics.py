def make_objective(kinematics):
    parameters = builtin_parameters(kinematics.model)
    targets = prepare_targets(SOURCE, thumb_rel_skip_proximal=parameters['thumb_rel_skip_proximal'])
    return FrameObjective(SOURCE, targets['edges'], directions=targets['directions'],
                          laplacian=targets['L'], differential=targets['D'],
                          weights=targets['row_weights'], thumb_triplets=targets['thumb_triplets'],
                          params=parameters, q_ref=Q * .8 + np.arange(20) * .003,
                          antirev_indices=kinematics.antirev_indices)


class RetargetNumericsTests(unittest.TestCase):
    def test_position_jacobians_against_finite_differences(self):
        """Differentiate observed positions, independently of analytic J math."""
        h = 1e-6
        for model, side in CASES:
            kinematics = HandKinematics(model, side)
            near_zero = Q * .37
            near_zero[[2, 6, 10, 14, 18]] = [-1e-4, 1e-8, -1e-8, 0., 1e-4]
            for label, q in [('curved', Q), ('near_zero', near_zero)]:
                with self.subTest(model=model, side=side, pose=label):
                    _, analytic = kinematics.forward(q)
                    numerical = np.empty_like(analytic)
                    for j in range(20):
                        delta = np.zeros(20)
                        delta[j] = h
                        numerical[:, :, j] = (kinematics.forward(q + delta)[0] -
                                              kinematics.forward(q - delta)[0]) / (2. * h)
                    np.testing.assert_allclose(analytic, numerical, rtol=2e-6, atol=2e-9)

    def test_objective_gradients_against_finite_differences(self):
        """Check both stages including thumb bending and negative-flexion cost."""
        h = 1e-6
        for model, side in CASES:
            kinematics = HandKinematics(model, side)
            objective = make_objective(kinematics)
            positions, jacobians = kinematics.forward(Q)
            for stage in (1, 2):
                with self.subTest(model=model, side=side, stage=stage):
                    _, analytic, terms = objective.evaluate(Q, positions, jacobians, stage)
                    self.assertGreater(terms['antireverse'], 0.)
                    self.assertGreater(terms['thumb_relative'], 0.)
                    numerical = np.empty(20)
                    for j in range(20):
                        delta = np.zeros(20)
                        delta[j] = h
                        plus = Q + delta
                        minus = Q - delta
                        fp = objective.evaluate(plus, *kinematics.forward(plus), stage)[0]
                        fm = objective.evaluate(minus, *kinematics.forward(minus), stage)[0]
                        numerical[j] = (fp - fm) / (2. * h)
                    np.testing.assert_allclose(analytic, numerical, rtol=3e-6, atol=3e-8)

    @unittest.skipUnless(sys.platform == 'linux' and platform.machine().lower() in ('x86_64', 'amd64')
                         and _native_sincos is not None,
                         'Frozen bit patterns target the pinned Linux x86-64 SDK/libm environment')
    def test_frozen_native_arithmetic(self):
        """Catch ULP drift that derivative tolerances cannot detect."""
        for model, side in CASES:
            kinematics = HandKinematics(model, side)
            positions, jacobians = kinematics.forward(Q)
            objective = make_objective(kinematics)
            observed = {'positions': positions[[4, 8, 20]].ravel(),
                        'jacobian': [jacobians[index] for index in JACOBIAN_INDICES]}
            for stage in (1, 2):
                cost, gradient, _ = objective.evaluate(Q, positions, jacobians, stage)
                observed['stage' + str(stage)] = [cost, *gradient[GRADIENT_INDICES]]
            for field, values in observed.items():
                with self.subTest(model=model, side=side, field=field):
                    expected = np.array([float.fromhex(value)
                                         for value in NATIVE[model + '_' + side][field]])
                    actual = np.asarray(values, dtype=np.float64)
                    np.testing.assert_array_equal(actual.view(np.uint64), expected.view(np.uint64))


