assert.match(vm.runInContext('cardWindowLabel(frame)',context),/单帧实时 · 无未来帧缓冲/);
assert.match(fs.readFileSync('moxian_web/static/index.html','utf8'),/wuji-view\.js\?v=card-future3-rtc-prefix-v3/);
