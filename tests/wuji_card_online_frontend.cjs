const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const context=vm.createContext({document:{getElementById:()=>({addEventListener(){}})},window:{addEventListener(){}}});
vm.runInContext(fs.readFileSync('moxian_web/static/wuji-view.js','utf8').replace(/^import .*;\n/gm,''),context);
assert.equal(vm.runInContext('cardWindowLabel({})',context),'');
context.frame={buffer_delay_frames:3,buffer_delay_ms:33.333,source_age_ms:120};
assert.match(vm.runInContext('cardWindowLabel(frame)',context),/前瞻 3 帧 · 缓冲 33.3 ms · 总延迟 120 ms/);
